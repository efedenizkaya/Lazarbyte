import org.gradle.api.tasks.Exec

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose.compiler)
}

android {
    namespace = "app.lazarbyte"
    // 37, not the Play targetSdk (36): the Compose libraries in the BOM
    // require compiling against API 37, while the app still targets 36.
    compileSdk = 37

    defaultConfig {
        applicationId = "app.lazarbyte"
        // uniffi and the SAF APIs used here are all available at this level.
        minSdk = 24
        // The Play Store requirement for new apps and updates since 2026-08-31.
        targetSdk = 36
    }

    buildFeatures {
        compose = true
    }

    // The Rust libraries are laid out per ABI by collectRustJniLibs, and the
    // Kotlin bindings are generated by generateUniffiBindings; both tasks are
    // wired into preBuild below. Plain paths: AGP 9 rejects Provider instances
    // here, and the explicit preBuild dependency carries the ordering.
    sourceSets {
        getByName("main") {
            jniLibs.srcDir("build/rust/jniLibs")
            // Built-in Kotlin (AGP 9) compiles from the kotlin source set; the
            // java one is not read for .kt files.
            kotlin.srcDir("build/generated/uniffi/kotlin")
        }
    }
}

dependencies {
    implementation("net.java.dev.jna:jna:${libs.versions.jna.get()}@aar")
    implementation(platform(libs.compose.bom))
    implementation(libs.compose.material3)
    implementation(libs.compose.ui)
    implementation(libs.compose.ui.tooling.preview)
    implementation(libs.activity.compose)
}

// The Rust side of the bridge. Versions and flags live in the root Cargo
// workspace; nothing here duplicates build logic, it only invokes it.
val rustAbis = mapOf(
    "arm64-v8a" to "aarch64-linux-android",
    "x86_64" to "x86_64-linux-android",
)

tasks.register<Exec>("buildRust") {
    description = "Builds liblazarbyte_ffi.so for both ABIs with cargo-ndk."
    workingDir = rootDir.parentFile
    commandLine(
        "cargo", "ndk", "--platform", "21",
        "-t", "arm64-v8a", "-t", "x86_64",
        "build", "--profile", "android", "-p", "lazarbyte-ffi",
    )
}

tasks.register<Copy>("collectRustJniLibs") {
    description = "Lays the built libraries out for packaging (arm64-v8a/, x86_64/)."
    dependsOn("buildRust")
    into(layout.buildDirectory.dir("rust/jniLibs"))
    for ((abi, triple) in rustAbis) {
        from(rootDir.parentFile.resolve("target/$triple/android/liblazarbyte_ffi.so")) {
            into(abi)
        }
    }
}

tasks.register<Exec>("generateUniffiBindings") {
    description = "Generates the Kotlin bindings from the built library."
    dependsOn("buildRust")
    workingDir = rootDir.parentFile
    commandLine(
        "cargo", "run", "-q", "-p", "uniffi-bindgen", "generate",
        "--library", "target/x86_64-linux-android/android/liblazarbyte_ffi.so",
        "--language", "kotlin",
        "--out-dir", "android/app/build/generated/uniffi/kotlin",
    )
}

tasks.named("preBuild") {
    dependsOn("collectRustJniLibs", "generateUniffiBindings")
}
